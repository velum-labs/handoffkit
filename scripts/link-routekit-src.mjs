#!/usr/bin/env node
/**
 * Escape hatch for developing FusionKit against a sibling RouteKit checkout.
 *
 * Writes a gitignored `.pnpmfile.cjs` that rewrites `@velum-labs/routekit*`
 * dependencies to `link:../routekit/packages/<dir>`. Use `--unlink` to remove it.
 *
 * After linking/unlinking, re-run `pnpm install`.
 */
import { existsSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pnpmfilePath = join(root, ".pnpmfile.cjs");
const unlink = process.argv.includes("--unlink");

/** Package name -> path relative to handoffkit root (sibling routekit checkout). */
const PACKAGE_LINKS = {
  "@velum-labs/routekit": "../routekit/packages/cli",
  "@velum-labs/routekit-accounts": "../routekit/packages/accounts",
  "@velum-labs/routekit-cli-core": "../routekit/packages/cli-core",
  "@velum-labs/routekit-cli-ui": "../routekit/packages/cli-ui",
  "@velum-labs/routekit-config": "../routekit/packages/config",
  "@velum-labs/routekit-config-core": "../routekit/packages/config-core",
  "@velum-labs/routekit-contracts": "../routekit/packages/contracts",
  "@velum-labs/routekit-control": "../routekit/packages/control",
  "@velum-labs/routekit-daemon": "../routekit/packages/daemon",
  "@velum-labs/routekit-gateway": "../routekit/packages/gateway",
  "@velum-labs/routekit-harness-core": "../routekit/packages/harness-core",
  "@velum-labs/routekit-registry": "../routekit/packages/registry",
  "@velum-labs/routekit-router": "../routekit/packages/router",
  "@velum-labs/routekit-runtime": "../routekit/packages/runtime",
  "@velum-labs/routekit-telemetry-core": "../routekit/packages/telemetry-core",
  "@velum-labs/routekit-testkit": "../routekit/packages/testkit",
  "@velum-labs/routekit-tool-claude": "../routekit/packages/tool-claude",
  "@velum-labs/routekit-tool-codex": "../routekit/packages/tool-codex",
  "@velum-labs/routekit-tool-cursor": "../routekit/packages/tool-cursor",
  "@velum-labs/routekit-tool-opencode": "../routekit/packages/tool-opencode",
  "@velum-labs/routekit-tool-registry": "../routekit/packages/tool-registry",
  "@velum-labs/routekit-tools": "../routekit/packages/tools",
  "@velum-labs/routekit-tracing": "../routekit/packages/tracing"
};

if (unlink) {
  if (existsSync(pnpmfilePath)) {
    unlinkSync(pnpmfilePath);
    console.log(`removed ${pnpmfilePath}`);
  } else {
    console.log("no .pnpmfile.cjs to remove");
  }
  console.log("Re-run: pnpm install");
  process.exit(0);
}

const missing = Object.entries(PACKAGE_LINKS)
  .filter(([, rel]) => !existsSync(join(root, rel)))
  .map(([name, rel]) => `${name} -> ${rel}`);
if (missing.length > 0) {
  console.error(
    "Sibling RouteKit checkout is incomplete. Expected packages under ../routekit/packages/:\n" +
      missing.map((line) => `  - ${line}`).join("\n")
  );
  process.exit(1);
}

const mappingLiteral = JSON.stringify(PACKAGE_LINKS, null, 2);
const contents = `// GENERATED by scripts/link-routekit-src.mjs — do not commit.
// Rewrites @velum-labs/routekit* deps to a sibling ../routekit checkout.
"use strict";

const PACKAGE_LINKS = ${mappingLiteral};

function rewriteDependency(version, name) {
  const target = PACKAGE_LINKS[name];
  if (target === undefined) return version;
  return \`link:\${target}\`;
}

function rewriteDeps(deps) {
  if (deps == null || typeof deps !== "object") return deps;
  const next = { ...deps };
  for (const name of Object.keys(next)) {
    next[name] = rewriteDependency(next[name], name);
  }
  return next;
}

module.exports = {
  hooks: {
    readPackage(pkg) {
      pkg.dependencies = rewriteDeps(pkg.dependencies);
      pkg.devDependencies = rewriteDeps(pkg.devDependencies);
      pkg.optionalDependencies = rewriteDeps(pkg.optionalDependencies);
      pkg.peerDependencies = rewriteDeps(pkg.peerDependencies);
      return pkg;
    }
  }
};
`;

writeFileSync(pnpmfilePath, contents);
console.log(`wrote ${pnpmfilePath}`);
console.log("Re-run: pnpm install");
console.log("To restore published packages: pnpm run dev:link-routekit-src -- --unlink && pnpm install");
